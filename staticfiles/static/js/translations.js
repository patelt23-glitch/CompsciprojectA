window.getTranslation = function(lang, key, params) {
  const dict = window.TRANSLATIONS[lang] || window.TRANSLATIONS['English'];
  let text = dict[key] || window.TRANSLATIONS['English'][key] || key;
  if (params && typeof params === 'object') {
    Object.keys(params).forEach(p => {
      text = text.replace(new RegExp(`\\{${p}\\}`, 'g'), params[p]);
    });
  }
  return text;
};
